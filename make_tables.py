#!/usr/bin/env python3
"""Turn returned results into LaTeX tables for Sec. 7 (no hand-copied numbers).

usage: python3 make_tables.py results_dir [results_dir ...] > ../neith-ace/sections/eval_tables.tex
Looks for bench_*.json, attacks_*.csv, live_*/live_*/windows.csv + summary.json.
"""
import csv, glob, json, os, statistics, sys

def q(xs, p):
    xs = sorted(xs); return xs[int(p * (len(xs) - 1))] if xs else float("nan")

def bench_tables(files):
    out = []
    for f in files:
        b = json.load(open(f)); host = b["host"].replace("_", r"\_")
        rows = []
        for k, v in sorted(b["hash"].items(), key=lambda kv: kv[1]["median_us"]):
            name, L = k.rsplit("@", 1)
            rows.append(f"{name} & {L} & {v['median_us']:.1f} & {v['MBps']:.2f}\\\\")
        out.append(rf"""\begin{{table}}[t]\centering
\caption{{Per-leaf hash cost on {host}.}}\label{{tab:hash-{b['host']}}}
\begin{{tabular}}{{@{{}}lrrr@{{}}}}\toprule
Instantiation & $L$ (B) & Median ($\mu$s) & MB/s\\\midrule
""" + "\n".join(rows) + r"""
\bottomrule\end{tabular}\end{table}""")
        mrows = [f"{k.rsplit('@',1)[0]} & {v['median_us']:.1f}\\\\" for k, v in sorted(b["mac"].items())]
        xrows = [f"{p.split('_')[1]} & {v['sig_bytes']} & {v['keygen_s']:.1f} & {v['sign_ms_median']:.2f} & "
                 f"{v['sign_ms_p95']:.2f} & {v['verify_ms_median']:.2f}\\\\" for p, v in sorted(b["xmss"].items())]
        out.append(rf"""\begin{{table}}[t]\centering
\caption{{Tag and checkpoint costs on {host}.}}\label{{tab:sig-{b['host']}}}
\begin{{tabular}}{{@{{}}lr@{{}}}}\toprule MAC (8\,KiB chunk) & Median ($\mu$s)\\\midrule
""" + "\n".join(mrows) + r"""
\bottomrule\end{tabular}\quad
\begin{tabular}{@{}rrrrrr@{}}\toprule $h$ & Sig.\ (B) & Keygen (s) & Sign med.\ (ms) & Sign p95 (ms) & Verify (ms)\\\midrule
""" + "\n".join(xrows) + r"""
\bottomrule\end{tabular}\end{table}""")
    return out

def attack_table(files):
    out = []
    for f in files:
        rows = list(csv.DictReader(open(f)))
        body = [f"{r['position']} & {r['scenario']} & {r['passed']}/{r['trials']} & "
                f"{next(iter(json.loads(r['verdicts'])))} & {float(r['verify_ms_median']):.1f}\\\\" for r in rows]
        host = os.path.basename(f)[8:-4].replace("_", r"\_")
        out.append(r"""\begin{table}[t]\centering
\caption{Attack injection results.}\label{tab:attack-results}
\begin{tabular}{@{}lllrr@{}}\toprule Position & Scenario & Correct & Verdict & Verify (ms)\\\midrule
""" + "\n".join(body) + r"""
\bottomrule\end{tabular}\end{table}""" + f"\n% source: {f} ({host})")
    return out

def live_table(dirs):
    out = []
    for d in dirs:
        rows = [r for r in csv.DictReader(open(os.path.join(d, "windows.csv"))) if r["phase"] == "telemetry"]
        s = json.load(open(os.path.join(d, "summary.json")))
        em = [float(r["emit_latency_s"]) for r in rows]; cp = [float(r["compute_s"]) for r in rows]
        rl = [float(r["receipt_latency_s"]) for r in rows if r.get("receipt_latency_s")]
        out.append(f"% live run {d}: windows={len(rows)} verdict={s['verdict']} dropped={s['dropped']} "
                   f"absences={s['n_absences']} match={s['absences_match_injected']}\n"
                   f"% E_t-T_t s: median={statistics.median(em):.4f} p95={q(em,.95):.4f} max={max(em):.4f}; "
                   f"compute ms: median={1e3*statistics.median(cp):.2f} max={1e3*max(cp):.2f}; "
                   f"receipt latency s: median={statistics.median(rl):.4f} p95={q(rl,.95):.4f} max={max(rl):.4f}; "
                   f"verify ms={1e3*s['verify_s']:.1f}; leaves={sum(int(r['N']) for r in rows)}")
    return out

def main():
    roots = sys.argv[1:] or ["results"]
    bf = sum((glob.glob(os.path.join(r, "**", "bench_*.json"), recursive=True) for r in roots), [])
    af = sum((glob.glob(os.path.join(r, "**", "attacks_*.csv"), recursive=True) for r in roots), [])
    lf = sum((glob.glob(os.path.join(r, "**", "live_*", "live_*"), recursive=True) for r in roots), [])
    lf = [d for d in lf if os.path.isdir(d) and os.path.exists(os.path.join(d, "summary.json"))]
    print("% generated by make_tables.py from: " + ", ".join(sorted(bf + af + lf)))
    for block in bench_tables(bf) + attack_table(af) + live_table(lf):
        print(block); print()

if __name__ == "__main__":
    main()
